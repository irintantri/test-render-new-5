// Sends the built app/ to Replit by pushing it to a GitHub repo connected to
// a repl's Git pane (Tools -> Git -> Create Remote / Connect Existing). This
// is the "send the package" half of build+render: Replit has no public API
// to accept a package and build/deploy it directly (see REPLIT_GUIDE.md), so
// this script treats app/ as its own throwaway git repo and force-pushes it
// to the branch your repl's Git pane tracks. After a push, open the repl and
// Pull, then Publish -- Replit does not (yet) auto-deploy on push.
//
// Only app/ makes this trip -- spec/ (and every design asset in it) is left
// behind in the bundle. Left alone, that means the repo Replit ends up with
// carries no replit.md and no design reference at all, so Replit Agent has
// nothing to compare the UI against and free-styles its own look on any
// further change. To close that gap, this script also refreshes
// app/.design-reference/ from spec/assets/ and writes a fresh app/replit.md
// pointing Agent at it, so both travel with every push (see
// syncDesignReference() below).
//
// Invoked by build.sh as the final step when REPLIT_GIT_REMOTE is set; run
// directly with `node replit.js` for the same effect.
//
// Env vars:
//   REPLIT_GIT_REMOTE  (required) the GitHub remote URL from the repl's Git
//                      pane, e.g. https://github.com/you/your-repl.git — for
//                      a private repo, bake a PAT into the URL yourself
//                      (https://<token>@github.com/you/your-repl.git) or rely
//                      on an existing git credential helper.
//   REPLIT_GIT_BRANCH  branch to push to (default: main) — match whatever
//                      branch the repl's Git pane is tracking.

'use strict';

const { execFileSync } = require('node:child_process');
const { existsSync, cpSync, mkdirSync, rmSync, writeFileSync } = require('node:fs');
const path = require('node:path');

const APP_DIR = path.resolve(__dirname, 'app');
const SPEC_ASSETS_DIR = path.resolve(__dirname, 'spec', 'assets');
const DESIGN_REFERENCE_DIR = path.join(APP_DIR, '.design-reference');
const REMOTE_NAME = 'replit';
const REMOTE_URL = process.env.REPLIT_GIT_REMOTE;
const BRANCH = process.env.REPLIT_GIT_BRANCH || 'main';

// Refreshes app/.design-reference/ from spec/assets/ and (re)writes
// app/replit.md so Replit Agent -- which after this push only ever sees
// app/, never spec/ -- still has the design spec to hold the UI to. Runs on
// every deploy, before `git add -A`, so both are staged and pushed. Always
// clears any previous copy first: app/ is regenerated output pushed with
// --force (see below), and a stale asset left over from an earlier spec
// would otherwise linger forever, silently going out of sync.
function syncDesignReference() {
  rmSync(DESIGN_REFERENCE_DIR, { recursive: true, force: true });
  const hasAssets = existsSync(SPEC_ASSETS_DIR);
  if (hasAssets) {
    mkdirSync(DESIGN_REFERENCE_DIR, { recursive: true });
    cpSync(SPEC_ASSETS_DIR, path.join(DESIGN_REFERENCE_DIR, 'assets'), { recursive: true });
  }
  writeFileSync(path.join(APP_DIR, 'replit.md'), designReplitMd(hasAssets));
  return hasAssets;
}

function designReplitMd(hasAssets) {
  if (!hasAssets) {
    return [
      '# replit.md',
      '',
      'This app was generated by Kolosal PlanOut and pushed here by replit.js --',
      'the "send the package" half of build+render (see REPLIT_GUIDE.md in the',
      'bundle this was built from). No design reference assets were bundled with',
      'this build.',
      '',
    ].join('\n');
  }
  return [
    '# replit.md',
    '',
    '## Design parity',
    '',
    "This app was generated to match a design spec. `.design-reference/assets/`",
    "carries that spec's visual source of truth, refreshed here on every deploy:",
    '',
    '- `<node_id>.png` -- pixel reference for layout, spacing, colors, radii, and typography.',
    '- `<node_id>.svg` -- original artwork; reuse directly for icons/illustrations.',
    '- `<node_id>.structure.txt` -- structural hints for layout.',
    '- `html/<node_id>.html` -- wireframe reference for UI structure/markup.',
    '- `attachments/<node_id>-N.<ext>` -- designer-pinned reference media (screenshots, mockups, brand assets).',
    '',
    'Before making any change to this app -- a fix, a feature, a restyle request -- check the',
    'relevant `.design-reference/assets/` files first and preserve visual parity (layout,',
    'spacing, colors, typography) with them. Do not introduce a different visual style, and do',
    'not redesign beyond what the requested change actually needs.',
    '',
  ].join('\n');
}

function git(args, opts = {}) {
  // stdio 'pipe' so an expected-to-fail probe (e.g. checking whether a
  // remote/identity is already configured) doesn't print git's own error to
  // the user's terminal — callers that catch and continue rely on that.
  return execFileSync('git', args, { cwd: APP_DIR, encoding: 'utf-8', stdio: 'pipe', ...opts });
}

function gitInherit(args) {
  execFileSync('git', args, { cwd: APP_DIR, stdio: 'inherit' });
}

function main() {
  if (!REMOTE_URL) {
    console.error('error: REPLIT_GIT_REMOTE is not set — nothing to push to.');
    console.error('Get it from your repl: Tools -> Git -> Create Remote (or Connect Existing).');
    process.exit(1);
  }

  if (!existsSync(APP_DIR)) {
    console.error(`error: ${APP_DIR} does not exist — run a build first so app/ exists.`);
    process.exit(1);
  }

  const hasGit = existsSync(path.join(APP_DIR, '.git'));
  if (!hasGit) {
    git(['init', '-q']);
    // Sets the initial branch name without depending on `git init -b`
    // support (added in git 2.28); works on older git too.
    git(['symbolic-ref', 'HEAD', `refs/heads/${BRANCH}`]);
  }

  const hasDesignAssets = syncDesignReference();
  console.log(
    hasDesignAssets
      ? '→ synced design reference (spec/assets/) into app/.design-reference/'
      : '→ no spec/assets/ found; skipped design reference sync',
  );

  // Only set a fallback identity when the repo has none configured — never
  // override an identity the user (or their global config) already set.
  try {
    git(['config', 'user.email']);
  } catch {
    git(['config', 'user.email', 'build-bot@kolosal.ai']);
    git(['config', 'user.name', 'Kolosal Build Bot']);
  }

  try {
    git(['remote', 'get-url', REMOTE_NAME]);
    git(['remote', 'set-url', REMOTE_NAME, REMOTE_URL]);
  } catch {
    git(['remote', 'add', REMOTE_NAME, REMOTE_URL]);
  }

  git(['add', '-A']);
  try {
    git(['commit', '-q', '-m', `Automated deploy — ${new Date().toISOString()}`]);
  } catch {
    console.log('→ no changes since the last deploy; pushing current state anyway.');
  }

  console.log(`→ pushing app/ to ${REMOTE_URL} (${BRANCH})...`);
  gitInherit(['push', REMOTE_NAME, `HEAD:${BRANCH}`, '--force']);

  console.log('');
  console.log('✅ pushed. In your repl: open the Git pane -> Pull, then Publish to make it live.');
  console.log('   (Replit does not auto-deploy on push yet — see REPLIT_GUIDE.md.)');
}

main();
